#!/bin/sh
# wiz-keepalive.sh
#
# Keeps Wi-Fi lighting clients (WiZ fixtures and similar) associated with the
# access point by sweeping the local subnet on a fixed interval. Sleeping
# clients that go quiet get aged out of the AP and drop off the controller.
#
# Generic: works on any Raspberry Pi / Debian-family Linux with a wired or
# wireless connection. Auto-detects the subnet and the tooling present.
#
# Usage (run ON the Pi, as root or with sudo):
#   sudo sh wiz-keepalive.sh install
#   sudo sh wiz-keepalive.sh remove
#   sudo sh wiz-keepalive.sh status
#   sudo sh wiz-keepalive.sh run
#
# install: sets up a scheduled job every 10 minutes (offset per minute so
#          multiple units on site do not all sweep at the same second)
# remove:  removes the job
# status:  shows what is installed
# run:     runs one sweep immediately
#
# Sweep method, in order of preference:
#   nmap -sn  host discovery (ARP) when nmap is installed
#   ping -b   broadcast ping when nmap is not available

WRAPPER=/usr/local/bin/wiz-keepalive-sweep
CRONFILE=/etc/cron.d/wiz-keepalive
UNITFILE=/etc/systemd/system/wiz-keepalive.service
TIMERFILE=/etc/systemd/system/wiz-keepalive.timer
INTERVAL=10

log() { echo "wiz-keepalive: $*"; }
die() { log "$*"; exit 1; }

detect_cidr() {
    _dev=$(ip route show default 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
    [ -n "$_dev" ] || _dev=$(ip -4 addr show scope global 2>/dev/null | awk '/:/ {print $2; exit}')
    [ -n "$_dev" ] || return 1
    ip -4 addr show dev "$_dev" 2>/dev/null | awk '/inet /{print $2; exit}'
}

write_wrapper() {
    cat > "$WRAPPER" <<'EOF'
#!/bin/sh
# wiz-keepalive sweep, generated by wiz-keepalive.sh
CIDR=""
DEV=$(ip route show default 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}')
[ -n "$DEV" ] || DEV=$(ip -4 addr show scope global 2>/dev/null | awk '/:/ {print $2; exit}')
if [ -n "$DEV" ]; then
    CIDR=$(ip -4 addr show dev "$DEV" 2>/dev/null | awk '/inet /{print $2; exit}')
fi
[ -n "$CIDR" ] || exit 0
if [ -x /usr/bin/nmap ]; then
    nmap -sn -n -T4 --max-retries 1 --host-timeout 5s "$CIDR" >/dev/null 2>&1
else
    BRD=$(ip -4 addr show dev "$DEV" 2>/dev/null | awk '/inet /{for(i=1;i<=NF;i++) if($i=="brd"){print $(i+1); exit}}')
    [ -n "$BRD" ] || BRD=$(echo "$CIDR" | sed 's/\.[0-9]*\/[0-9]*$/.255/')
    ping -b -c 1 -W 1 "$BRD" >/dev/null 2>&1
fi
EOF
    chmod 755 "$WRAPPER"
}

install_cron() {
    printf '%s\n' "3,13,23,33,43,53 * * * * root $WRAPPER" > "$CRONFILE"
    chmod 644 "$CRONFILE"
}

install_timer() {
    cat > "$UNITFILE" <<EOF
[Unit]
Description=WiZ keepalive sweep

[Service]
Type=oneshot
ExecStart=$WRAPPER
EOF
    cat > "$TIMERFILE" <<EOF
[Unit]
Description=Run WiZ keepalive sweep every $INTERVAL minutes

[Timer]
OnBootSec=2min
OnUnitActiveSec=${INTERVAL}min
AccuracySec=30s

[Install]
WantedBy=timers.target
EOF
    systemctl daemon-reload
    systemctl enable --now wiz-keepalive.timer
}

install_nmap() {
    if [ -x /usr/bin/nmap ]; then
        log "nmap present, using host discovery"
        return 0
    fi
    if command -v apt-get >/dev/null 2>&1; then
        log "installing nmap"
        if DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nmap >/dev/null 2>&1; then
            log "nmap installed"
            return 0
        fi
    fi
    log "nmap unavailable, using broadcast ping instead"
}

# discover lists hosts on the local subnet that look like a hub, by checking
# which ones answer on the ports the hub's web interface uses.
discover() {
    cidr=$(detect_cidr) || die "could not detect a network interface"
    log "scanning $cidr"
    if [ -x /usr/bin/nmap ]; then
        nmap -sn -n -T4 --host-timeout 5s "$cidr" 2>/dev/null | awk '/Nmap scan report/{print $NF}' > /tmp/wiz-hosts.$$
    else
        base=$(echo "$cidr" | cut -d. -f1-3)
        for i in $(seq 1 254); do
            ping -c 1 -W 1 "$base.$i" >/dev/null 2>&1 && echo "$base.$i"
        done > /tmp/wiz-hosts.$$
    fi
    log "hosts answering:"
    while read -r h; do
        [ -n "$h" ] || continue
        if command -v nc >/dev/null 2>&1; then
            for p in 80 443 5500; do
                nc -z -w 1 "$h" "$p" >/dev/null 2>&1 && { echo "  $h  (hub, port $p)"; continue 2; }
            done
            echo "  $h  (no hub ports open)"
        else
            echo "  $h"
        fi
    done < /tmp/wiz-hosts.$$
    rm -f /tmp/wiz-hosts.$$
}

case "$1" in
    install)
        [ "$(id -u)" = 0 ] || die "run as root or with sudo"
        cidr=$(detect_cidr) || die "could not detect a network interface"
        log "subnet $cidr"
        install_nmap
        write_wrapper
        if [ -x /usr/sbin/cron ] || [ -x /usr/bin/crontab ]; then
            install_cron
            systemctl enable cron 2>/dev/null
            systemctl start cron 2>/dev/null
            log "installed: sweep every $INTERVAL minutes via cron"
        elif command -v systemctl >/dev/null 2>&1; then
            install_timer
            log "installed: sweep every $INTERVAL minutes via systemd timer"
        else
            die "no cron or systemd available to schedule the job"
        fi
        log "run 'sh $0 status' to check"
        ;;
    remove)
        [ "$(id -u)" = 0 ] || die "run as root or with sudo"
        rm -f "$CRONFILE" "$UNITFILE" "$TIMERFILE" "$WRAPPER"
        systemctl daemon-reload 2>/dev/null
        systemctl disable --now wiz-keepalive.timer 2>/dev/null
        log "removed"
        ;;
    status)
        if [ -f "$CRONFILE" ]; then
            log "installed via cron:"
            cat "$CRONFILE"
        elif [ -f "$TIMERFILE" ]; then
            log "installed via systemd timer:"
            systemctl list-timers wiz-keepalive.timer --no-pager 2>/dev/null | head -3
        else
            log "not installed"
        fi
        cidr=$(detect_cidr) || true
        log "subnet ${cidr:-unknown}"
        if [ -x /usr/bin/nmap ]; then log "method: nmap"; else log "method: broadcast ping"; fi
        ;;
    run)
        cidr=$(detect_cidr) || die "could not detect a network interface"
        log "sweeping $cidr"
        [ -f "$WRAPPER" ] || write_wrapper
        sh "$WRAPPER"
        log "done"
        ;;
    discover)
        discover
        ;;
    *)
        echo "usage: sudo sh $0 install|remove|status|run|discover"
        exit 1
        ;;
esac
